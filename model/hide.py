# -*- coding: utf-8 -*-
"""Вычет зверя из его же шкуры.

Игровое сопротивление у существ размечено осмысленно — авторы растили его с уровнем, от
нуля у лошади до семидесяти пяти процентов у горгоны. Это готовая лестница шкуры, и её
довольно перевести в вычет, чтобы зверь встал в ту же модель, что и человек в доспехе:
стена, которую надо одолеть пробитием, а не потолок в восемьдесят процентов.

    вычет = сопротивление % × Hide × (1 + уровень × Growth)

Дальше всё как обычно: пробитие съедает вычет, остаток съедает урон.
"""

HIDE = 1.0        # во что превращается процент шкуры
GROWTH = 0.03     # насколько шкура крепчает за уровень

# Чем бьёт игрок: (ступень, стат, вес меча, вес топора, вес молота)
STAGES = [
    ("начало,  Т1, стат 10", 10, 3.00, 4.00, 8.00),
    ("середина, Т3, стат 25", 25, 4.29, 5.72, 11.44),
    ("конец,   Т5, стат 45", 45, 7.50, 10.00, 20.00),
]

# Кого меряем: имя, уровень, сопротивление режущему %
WHO = [
    ("Волк", 5, 10),
    ("Волчий король", 6, 15),
    ("Белый волк", 11, 10),
    ("Медведь", 14, 30),
    ("Гигантский паук", 28, 35),
    ("Оборотень", 31, 45),
    ("Минотавр", 35, 50),
    ("Порченый волк", 34, 50),
    ("Химера", 40, 55),
    ("Циклоп", 43, 60),
    ("Король червей", 55, 65),
    ("Дракон", 55, 65),
    ("Дракон на 300", 300, 65),
]


def guard(resist, level):
    return resist * HIDE * (1 + level * GROWTH)


print("%-20s %5s %6s %9s | %s" % ("зверь", "ур.", "шкура", "вычет", "кто пробивает"))
print("-" * 96)

for name, level, resist in WHO:
    wall = guard(resist, level)

    beats = []
    for label, stat, sword, axe, hammer in STAGES:
        tier = label.split(",")[1].strip()
        if stat * hammer >= wall:
            who = "молот"
            if stat * axe >= wall:
                who = "топор"
            if stat * sword >= wall:
                who = "меч"
            beats.append("%s %s" % (tier, who))

    print("%-20s %5d %5d%% %9.0f | %s" % (
        name, level, resist, wall, ", ".join(beats) if beats else "никто"))

print()
print("чем бьёт игрок:")
for label, stat, sword, axe, hammer in STAGES:
    print("  %-22s меч %4.0f  топор %4.0f  молот %4.0f" % (
        label, stat * sword, stat * axe, stat * hammer))

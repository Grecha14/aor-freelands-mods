        /// <summary>Makes the book, once, as early as the item database exists.</summary>
        internal static void Register()
        {
            if (registered || Enabled == null || !Enabled.Value) return;
            if (gameManager.GM == null) return;

            UIItemDatabase db;
            try { db = UIItemDatabase.Instance; }
            catch { return; }
            if (db == null || db.items == null || db.items.Length == 0) return;

            try
            {
                UIItemInfo copy = db.GetByID(BookId);
                bool fresh = copy == null;

                if (fresh)
                {
                    UIItemInfo pattern = null;
                    foreach (UIItemInfo one in db.items)
                    {
                        if (one != null && one.itemType == ItemType.Readable && one.name != null
                            && one.Name != null && one.Name.StartsWith("items_Readable_", StringComparison.Ordinal))
                        {
                            pattern = one;
                            break;
                        }
                    }
                    if (pattern == null)
                    {
                        foreach (UIItemInfo one in db.items)
                        {
                            if (one != null && one.itemType == ItemType.Readable) { pattern = one; break; }
                        }
                    }
                    if (pattern == null)
                    {
                        registered = true;
                        DemonLookPlugin.Log.LogWarning("Сказание: в игре не нашлось читаемой книги для образца.");
                        return;
                    }

                    copy = UnityEngine.Object.Instantiate(pattern);
                    copy.name = "DemonChronicle";
                    copy.ID = BookId;
                }

                copy.Name = Title;
                copy.Description = "Старое сказание о Владыках Ада: как они приходят в мир, чем живут и чего боятся.";
                copy.readContent = Text();
                copy.itemType = ItemType.Readable;
                copy.isUnique = true;
                copy.value = 0;

                if (fresh)
                {
                    List<UIItemInfo> all = new List<UIItemInfo>(db.items);
                    all.Add(copy);
                    db.items = all.ToArray();
                }

                book = copy;
                registered = true;
            }
            catch (Exception e)
            {
                registered = true;
                DemonLookPlugin.Log.LogError("Сказание: не смог завести книгу: " + e);
            }
        }

        /// <summary>Puts the book into the demon bag, once for this save.</summary>
        internal static void Give(HumaniodUnit demon)
        {
            if (book == null || demon == null || Souls.HasChronicle) return;

            try
            {
                if (InventoryManager.instance == null) return;
                InventoryManager.instance.PutItemInbag(new Inventory(book));
                Souls.HasChronicle = true;
                Souls.Say("В сумке — «" + Title + "». Прочтите: там всё, что знают о вашей породе.");
            }
            catch (Exception e)
            {
                DemonLookPlugin.Log.LogWarning("Сказание: не легло в сумку: " + e.Message);
            }
        }
